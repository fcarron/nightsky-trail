type TranslationKey = keyof (typeof translations)["de"];

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
  tx: (text: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: "de",
  setLocale: () => undefined,
  t: (key) => translations.de[key],
  tx: (text) => translateText("de", text),
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(loadLocale);

  useEffect(() => {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => ({
      locale,
      setLocale,
      t: (key) => translations[locale][key],
      tx: (text) => translateText(locale, text),
    }),
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

function translateText(locale: Locale, text: string): string {
  const key = Object.entries(translations.de).find(
    ([, value]) => value === text,
  )?.[0] as TranslationKey | undefined;
  return key
    ? translations[locale][key]
    : (phraseTranslations[locale][text] ?? text);
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

export function localeName(locale: Locale): string {
  return languageNames[locale];
}

function loadLocale(): Locale {
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return SUPPORTED_LOCALES.includes(stored as Locale)
    ? (stored as Locale)
    : "de";
}
